//! Phase 6 §6.1.3 — triplet notation (Wolfe §8.1.3).
//!
//! A [`Triplet`] is `[l : u : s]` — lower bound, upper bound, **stride**. The
//! stride is what simple bounds throw away: `A[2i]` over `i in [0,8)` touches
//! `{0,2,4,...,14}`, but [`super::bounds::Region`] can only say `[0:14]`, which
//! includes the odd elements the loop never reads. Union and intersection of
//! arithmetic progressions are settled exactly here:
//!
//! ```text
//! union         [la:ua:sa] U [lb:ub:sb]
//!               = [min la lb : max ua ub : gcd(sa, sb, la - lb)]
//!
//! intersection  solve  la + i*sa = lb + j*sb  for the least solution
//!               stride = lcm(sa, sb)
//! ```
//!
//! ## Why gcd for the union and lcm for the intersection
//!
//! The differences generated by `sa`, `sb` and `la - lb` are exactly the
//! multiples of `g = gcd(sa, sb, la-lb)`, so `g` is the finest lattice the union
//! still lives on. That is the Wolfe formula.
//!
//! For the intersection, an element must satisfy both congruences
//! `x = la (mod sa)` and `x = lb (mod sb)`, which the Chinese-remainder argument
//! makes solvable iff `gcd(sa, sb) | (la - lb)`; the solution set is then a
//! single congruence class modulo `lcm(sa, sb)`. So intersection *narrows* the
//! lattice while union *widens* it — the reason the union needs a three-argument
//! gcd and the intersection a two-argument one.
//!
//! ## Emptiness

//! An intersection with no solution is `None`, not an empty region: the callers
//! (`Kill` meets, containment checks) branch on "no common element", and a
//! zero-stride or inverted `Triplet` invites arithmetic that would divide by it.

use serde::{Deserialize, Serialize};

use crate::ir::{Access, IndexKind, IV, Loop};

use super::bounds::region_of_access;

/// One dimension of a triplet region: `(lower, upper, stride)`, bounds
/// inclusive, stride strictly positive.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct Triplet {
    pub lower: i64,
    pub upper: i64,
    /// Always `> 0`. A zero stride would mean "every iteration hits `lower`",
    /// which is already representable as `[l:l:1]`.
    pub stride: i64,
}

impl Triplet {
    pub fn new(lower: i64, upper: i64, stride: i64) -> Triplet {
        Triplet { lower, upper, stride: if stride <= 0 { 1 } else { stride } }
    }

    /// The single value `v`.
    pub fn point(v: i64) -> Triplet {
        Triplet { lower: v, upper: v, stride: 1 }
    }

    /// `true` when the triplet names no element.
    pub fn is_empty(&self) -> bool {
        self.stride <= 0 || self.lower > self.upper
    }

    /// `true` when `x` is one of the triplet's elements.
    pub fn contains(&self, x: i64) -> bool {
        !self.is_empty()
            && x >= self.lower
            && x <= self.upper
            && (x - self.lower).rem_euclid(self.stride) == 0
    }

    /// The `n`-th element: `lower + n*stride`.
    pub fn nth(&self, n: i64) -> Option<i64> {
        self.lower.checked_add(self.stride.checked_mul(n)?)
    }

    /// How many elements the triplet holds, or `None` if that overflows.
    pub fn count(&self) -> Option<i64> {
        if self.is_empty() {
            return Some(0);
        }
        Some((self.upper - self.lower) / self.stride + 1)
    }

    /// Every element, or `None` when there are more than `cap` of them.
    pub fn enumerate(&self, cap: usize) -> Option<Vec<i64>> {
        let n = self.count()?;
        if n > cap as i64 {
            return None;
        }
        let mut out = Vec::with_capacity(n as usize);
        let mut x = self.lower;
        while x <= self.upper {
            out.push(x);
            x = x.checked_add(self.stride)?;
        }
        Some(out)
    }

    /// Wolfe's triplet union: `[min l : max u : gcd(sa, sb, la-lb)]`.
    pub fn union(&self, other: &Triplet) -> Option<Triplet> {
        if self.is_empty() {
            return Some(*other);
        }
        if other.is_empty() {
            return Some(*self);
        }
        let stride = crate::solver::gcd::gcd_many(&[
            self.stride,
            other.stride,
            self.lower.checked_sub(other.lower)?,
        ]);
        Some(Triplet {
            lower: self.lower.min(other.lower),
            upper: self.upper.max(other.upper),
            stride: stride.max(1),
        })
    }

    /// Wolfe's triplet intersection: the least common element, then `lcm` as the
    /// stride.
    ///
    /// `None` when the two lattices share no element. The lower bound reported is
    /// the least common element actually found, not `max(la, lb)` — the widened
    /// box's lower corner is frequently *not* in either lattice, and anchoring
    /// there would make [`Triplet::contains`] wrong for the region's own points.
    pub fn intersect(&self, other: &Triplet) -> Option<Triplet> {
        if self.is_empty() || other.is_empty() {
            return None;
        }
        let lo = self.lower.max(other.lower);
        let hi = self.upper.min(other.upper);
        if lo > hi {
            return None;
        }
        let stride = lcm(self.stride, other.stride)?;
        if stride <= 0 {
            return None;
        }
        let start = self.lower.max(congruent_at_least(self.lower, self.stride, lo)?);
        let mut x = congruent_at_least(start, self.stride, lo)?;
        // At most one period of the coarser lattice needs checking: past
        // `lo + max(sa, sb)` the two congruences either have met or never will.
        let limit = lo.checked_add(self.stride.max(other.stride))?;
        while x <= hi.min(limit) + stride {
            if other.contains(x) {
                let last = (hi - x).div_euclid(stride) * stride + x;
                return Some(Triplet { lower: x, upper: last.max(x), stride });
            }
            x = x.checked_add(self.stride)?;
        }
        None
    }

    /// `true` when every element of `self` is an element of `other`: the ranges
    /// nest and `other`'s lattice contains `self`'s.
    pub fn is_subset_of(&self, other: &Triplet) -> bool {
        if self.is_empty() {
            return true;
        }
        if other.is_empty() {
            return false;
        }
        other.lower <= self.lower
            && self.upper <= other.upper
            && (self.lower - other.lower).rem_euclid(other.stride) == 0
            && self.stride.rem_euclid(other.stride) == 0
    }
}

/// The least integer `>= lo` with `x = base (mod stride)`.
fn congruent_at_least(base: i64, stride: i64, lo: i64) -> Option<i64> {
    if stride <= 0 {
        return None;
    }
    if lo <= base {
        return Some(base);
    }
    let d = lo.checked_sub(base)?;
    let k = d.div_euclid(stride) + if d.rem_euclid(stride) == 0 { 0 } else { 1 };
    base.checked_add(stride.checked_mul(k)?)
}

/// Least common multiple; `None` on overflow.
pub fn lcm(a: i64, b: i64) -> Option<i64> {
    if a == 0 || b == 0 {
        return None;
    }
    let g = crate::solver::gcd::gcd(a, b);
    // Both operands are made positive *before* the multiply: `a/g` keeps the
    // sign of `a`, so a negative stride would otherwise produce a negative lcm
    // and a `Triplet` whose stride fails `is_empty`.
    a.abs().checked_div(g)?.checked_mul(b.abs())
}

/// A multi-dimensional triplet region: one [`Triplet`] per dimension.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, Default)]
pub struct TripletRegion {
    pub dims: Vec<Triplet>,
}

impl TripletRegion {
    pub fn new(dims: Vec<Triplet>) -> TripletRegion {
        TripletRegion { dims }
    }

    /// A 1-D region from an inclusive `[lo, hi]` span at the given stride.
    pub fn span(lo: i64, hi: i64, stride: i64) -> TripletRegion {
        TripletRegion { dims: vec![Triplet::new(lo, hi, stride)] }
    }

    pub fn arity(&self) -> usize {
        self.dims.len()
    }

    pub fn is_empty(&self) -> bool {
        self.dims.is_empty() || self.dims.iter().any(Triplet::is_empty)
    }

    pub fn contains(&self, point: &[i64]) -> bool {
        self.arity() == point.len()
            && self.dims.iter().zip(point.iter()).all(|(d, &p)| d.contains(p))
    }

    /// Per-dimension union. `None` on arity mismatch.
    pub fn union(&self, other: &TripletRegion) -> Option<TripletRegion> {
        if self.arity() != other.arity() {
            return None;
        }
        let mut dims = Vec::with_capacity(self.arity());
        for (a, b) in self.dims.iter().zip(other.dims.iter()) {
            dims.push(a.union(b)?);
        }
        Some(TripletRegion { dims })
    }

    /// Per-dimension intersection; `None` if any dimension's lattices are
    /// disjoint or the arities disagree.
    pub fn intersect(&self, other: &TripletRegion) -> Option<TripletRegion> {
        if self.arity() != other.arity() {
            return None;
        }
        let mut dims = Vec::with_capacity(self.arity());
        for (a, b) in self.dims.iter().zip(other.dims.iter()) {
            dims.push(a.intersect(b)?);
        }
        Some(TripletRegion { dims })
    }

    /// `true` when every element of `self` lies in `other`.
    pub fn is_subset_of(&self, other: &TripletRegion) -> bool {
        if self.is_empty() {
            return true;
        }
        self.arity() == other.arity()
            && self.dims.iter().zip(other.dims.iter()).all(|(a, b)| a.is_subset_of(b))
    }

    /// Every point, or `None` when the region holds more than `cap` of them.
    pub fn enumerate(&self, cap: usize) -> Option<Vec<Vec<i64>>> {
        let mut total: i64 = 1;
        for d in &self.dims {
            total = total.checked_mul(d.count()?)?;
            if total > cap as i64 {
                return None;
            }
        }
        let mut out: Vec<Vec<i64>> = vec![vec![]];
        for d in &self.dims {
            let vals = d.enumerate(cap)?;
            let mut next = Vec::with_capacity(out.len() * vals.len().max(1));
            for prefix in &out {
                for &v in &vals {
                    let mut p = prefix.clone();
                    p.push(v);
                    next.push(p);
                }
            }
            out = next;
        }
        Some(out)
    }

    /// Downgrade to a plain box, forgetting the strides, for callers that state
    /// summaries in the §6.1.2 vocabulary.
    pub fn to_region(&self) -> super::bounds::Region {
        super::bounds::Region::new(self.dims.iter().map(|d| (d.lower, d.upper)).collect())
    }
}

/// The triplet region of an access, exact for the affine single-IV case.
///
/// `A[c*i + k]` over `i in [lo, hi]` step `t` is `[c*lo+k : c*hi+k : c*t]` for
/// `c > 0` (reversed for `c < 0`); `c == 0` is a single point.
///
/// `None` when nothing exact can be said: multi-dimensional index forms (the
/// mixed term is not one progression), non-affine index kinds, parametric
/// offsets, `RangeExpr` accesses, dead accesses. Callers then fall back to
/// [`super::bounds::region_of_access`], which is sound but coarser.
pub fn triplet_of_access(access: &Access, loop_: &Loop) -> Option<TripletRegion> {
    if access.range.is_some() {
        return None;
    }
    match &access.index_kind {
        IndexKind::Affine => {
            if access.index.len() != loop_.depth || loop_.depth != 1 {
                return None;
            }
            let offset = access.offset.as_const()?;
            let c = access.index[0];
            let iv = loop_.ivs.first()?;
            if iv.step <= 0 || iv.lower >= iv.upper {
                return None;
            }
            let last = (iv.upper - 1 - iv.lower) / iv.step * iv.step + iv.lower;
            // Guard narrowing reuses the box derivation, then re-anchors.
            let box_ = region_of_access(access, loop_)?;
            let stride = if c == 0 { 1 } else { (c.abs() as i64).checked_mul(iv.step)? };
            let lo = box_.dims[0].0.max(c.checked_mul(iv.lower)?.checked_add(offset)?);
            let hi = box_.dims[0].1.min(c.checked_mul(last)?.checked_add(offset)?);
            if lo > hi {
                return None;
            }
            // A zero coefficient makes the index invariant: one point.
            if c == 0 {
                return Some(TripletRegion::span(offset, offset, 1));
            }
            let _ = last;
            Some(TripletRegion::span(lo, hi, stride))
        }
        _ => None,
    }
}

/// The stride an affine access advances by per iteration, `None` if not affine.
pub fn access_stride(access: &Access, ivs: &[IV]) -> Option<i64> {
    let IndexKind::Affine = &access.index_kind else { return None };
    if access.index.len() != ivs.len() || ivs.is_empty() {
        return None;
    }
    let mut acc: i64 = 0;
    for (k, &c) in access.index.iter().enumerate() {
        acc = acc.checked_add(c.checked_mul(ivs[k].step)?)?;
    }
    Some(acc.abs().max(1))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{AccessKind, IndexExpr, OffsetValue};
    use super::super::bounds::Region;

    #[test]
    fn union_of_strided_regions_keeps_the_gcd_lattice() {
        // [0:14:2] U [1:13:2]: differences generated by 2, 2 and (0-1) are the
        // multiples of gcd(2,2,1) = 1, so the union really is every integer.
        let a = Triplet::new(0, 14, 2);
        let b = Triplet::new(1, 13, 2);
        let u = a.union(&b).unwrap();
        assert_eq!((u.lower, u.upper, u.stride), (0, 14, 1));
        for x in [0, 1, 7, 13, 14] {
            assert!(u.contains(x));
        }
        // Two even lattices union to the even lattice, not to all integers.
        let c = Triplet::new(2, 10, 4);
        let d = Triplet::new(0, 8, 2);
        let u2 = c.union(&d).unwrap();
        assert_eq!((u2.lower, u2.upper, u2.stride), (0, 10, 2));
    }

    #[test]
    fn intersection_solves_the_diophantine_and_uses_lcm() {
        // Even numbers and multiples of 3 intersect to multiples of 6.
        let a = Triplet::new(0, 30, 2);
        let b = Triplet::new(0, 30, 3);
        let i = a.intersect(&b).unwrap();
        assert_eq!(i.stride, 6);
        assert_eq!(i.lower, 0);
        assert_eq!(i.enumerate(64), Some(vec![0, 6, 12, 18, 24, 30]));
        // Anchored at 0 and 1: the first common element is 4, not max(0,1)=1.
        let c = Triplet::new(0, 30, 2);
        let d = Triplet::new(1, 30, 3);
        let i2 = c.intersect(&d).unwrap();
        assert_eq!(i2.lower, 4, "intersection must anchor on a real common element");
        assert!(i2.contains(4) && i2.contains(10) && !i2.contains(1));
    }

    #[test]
    fn disjoint_lattices_are_none() {
        // Even and odd share nothing: gcd(2,2)=2 does not divide 1.
        let a = Triplet::new(0, 10, 2);
        let b = Triplet::new(1, 9, 2);
        assert_eq!(a.intersect(&b), None);
        // Overlapping ranges, incompatible congruences.
        let c = Triplet::new(0, 30, 4);
        let d = Triplet::new(1, 30, 2);
        assert_eq!(c.intersect(&d), None);
    }

    #[test]
    fn subset_requires_nested_range_and_divisible_stride() {
        let fine = Triplet::new(0, 14, 2);
        let coarse = Triplet::new(0, 14, 1);
        assert!(fine.is_subset_of(&coarse));
        assert!(!coarse.is_subset_of(&fine));
        // Same lattice, one element wider: not a subset.
        assert!(!Triplet::new(0, 16, 2).is_subset_of(&coarse));
    }

    #[test]
    fn enumerate_matches_count_and_is_bounded() {
        let t = Triplet::new(3, 30, 7);
        assert_eq!(t.count(), Some(4));
        assert_eq!(t.enumerate(10), Some(vec![3, 10, 17, 24]));
        assert_eq!(t.enumerate(3), None);
        assert_eq!(Triplet::new(5, 1, 2).count(), Some(0));
        assert!(Triplet::new(5, 1, 2).is_empty());
    }

    #[test]
    fn triplet_of_an_affine_access_is_exact_where_the_box_is_not() {
        // A[2i] over i in [0,8): box [0:14] (which wrongly includes odd
        // elements), triplet [0:14:2] (which does not).
        let l = Loop {
            depth: 1,
            ivs: vec![IV::new("i", 0, 8, 1)],
            body: vec![],
            recursion: None,
            chase: None,
            assertions: vec![],
            scalars: vec![],
            stmts: None,
        };
        let a = Access {
            kind: AccessKind::Write,
            base: "A".into(),
            index: vec![2],
            elem_size: 8,
            offset: OffsetValue::Const(1),
            expr: None,
            indirect: None,
            guard: None,
            range: None,
            index_kind: IndexKind::Affine,
        };
        let t = triplet_of_access(&a, &l).unwrap();
        assert_eq!((t.dims[0].lower, t.dims[0].upper, t.dims[0].stride), (1, 15, 2));
        assert!(t.contains(&[1]) && t.contains(&[15]) && !t.contains(&[2]));
        // Every element of the triplet is a location the loop really visits,
        // and every location the loop visits is in the triplet: the exactness
        // the box form cannot claim.
        let visited = super::super::bounds::locations_of_access(&a, &l, 4096).unwrap();
        let tri = t.enumerate(4096).unwrap().into_iter().map(|p| p[0]).collect::<Vec<_>>();
        assert_eq!(tri, visited, "triplet must equal the enumerated locations exactly");
        // A loop-invariant write is a single point.
        let inv = Access { index: vec![0], ..a.clone() };
        let ti = triplet_of_access(&inv, &l).unwrap();
        assert_eq!((ti.dims[0].lower, ti.dims[0].upper), (1, 1));
    }

    #[test]
    fn multidimensional_and_nonaffine_accesses_refuse() {
        let l = Loop {
            depth: 2,
            ivs: vec![
                IV::new("i", 0, 4, 1),
                IV::new("j", 0, 4, 1),
            ],
            body: vec![],
            recursion: None,
            chase: None,
            assertions: vec![],
            scalars: vec![],
            stmts: None,
        };
        let a = Access {
            kind: AccessKind::Read,
            base: "A".into(),
            index: vec![1, 1],
            elem_size: 8,
            offset: OffsetValue::Const(0),
            expr: None,
            indirect: None,
            guard: None,
            range: None,
            index_kind: IndexKind::Affine,
        };
        // `i + j` is not one arithmetic progression, so no exact triplet.
        assert_eq!(triplet_of_access(&a, &l), None);
        let prod = Access {
            index_kind: IndexKind::Product(IndexExpr::Mul(
                Box::new(IndexExpr::IV(0)),
                Box::new(IndexExpr::IV(1)),
            )),
            ..a
        };
        assert_eq!(triplet_of_access(&prod, &l), None);
    }

    #[test]
    fn to_region_forgets_the_stride_but_keeps_the_box() {
        let t = TripletRegion::span(0, 14, 2);
        assert_eq!(t.to_region(), Region::span(0, 14));
    }

    #[test]
    fn lcm_refuses_zero_operands() {
        assert_eq!(lcm(4, 6), Some(12));
        assert_eq!(lcm(0, 6), None);
        assert_eq!(lcm(6, 0), None);
        assert_eq!(lcm(-4, 6), Some(12));
    }
}
